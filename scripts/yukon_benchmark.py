#!/usr/bin/env python3
"""Prepare the trusted Comparator challenge and publish the verified gas score."""

from __future__ import annotations

import csv
import json
import os
from pathlib import Path
import re
import sys


HEX_RE = re.compile(r"(?:[0-9a-f]{2})+")
EXPECTED_VECTOR_COUNT = 19


def _atomic_write(path: Path, contents: str, encoding: str = "utf-8") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(contents, encoding=encoding)
    os.replace(temporary, path)


def read_artifact(path: Path) -> tuple[str, str]:
    try:
        raw = path.read_text(encoding="ascii")
    except (OSError, UnicodeError) as error:
        raise ValueError(f"could not read ASCII bytecode from {path}: {error}") from error

    body = raw[:-1] if raw.endswith("\n") else raw
    if "\n" in body or "\r" in body or HEX_RE.fullmatch(body) is None:
        raise ValueError(
            "bytecode.hex must contain one nonempty line of lowercase byte pairs "
            "without a 0x prefix"
        )
    return raw, body


def render_artifact(artifact: str) -> str:
    values = bytes.fromhex(artifact)
    chunks = [values[offset : offset + 64] for offset in range(0, len(values), 64)]
    declarations: list[str] = []
    for index, chunk in enumerate(chunks):
        rows = []
        for offset in range(0, len(chunk), 12):
            row = ", ".join(f"0x{value:02x}" for value in chunk[offset : offset + 12])
            rows.append(f"  {row}")
        declarations.append(
            f"private abbrev artifactChunk{index} : ByteArray := ByteArray.mk #[\n"
            + ",\n".join(rows)
            + "\n]"
        )

    declarations_text = "\n\n".join(declarations)
    expression = " ++\n    ".join(f"artifactChunk{index}" for index in range(len(chunks)))
    return f"""\
/- Generated from the protected submission by scripts/yukon_benchmark.py. -/
import Challenge.Sha256.Benchmark.Target

namespace Challenge.Sha256.Benchmark

{declarations_text}

/-- The exact submitted bytes checked by Lean and scored by the EVM runner. -/
abbrev bytecode : ByteArray :=
  {expression}

end Challenge.Sha256.Benchmark
"""


def render_challenge() -> str:
    return """\
/- Generated by scripts/yukon_benchmark.py. Do not edit. -/
import Challenge.Sha256.Benchmark.Artifact

namespace Challenge.Sha256.Benchmark

theorem candidate : Challenge.Sha256.Correct bytecode := by
  sorry

end Challenge.Sha256.Benchmark
"""


def prepare(submitted: Path, trusted: Path, artifact_module: Path, challenge: Path) -> None:
    # Read the editable artifact once. The same exact bytes feed the protected
    # Lean module and the post-verification scorer, closing the TOCTOU gap.
    raw, artifact = read_artifact(submitted)
    _atomic_write(trusted, raw, "ascii")
    _atomic_write(artifact_module, render_artifact(artifact))
    _atomic_write(challenge, render_challenge())


def parse_score_csv(path: Path) -> tuple[int, int, int]:
    try:
        handle = path.open(newline="", encoding="utf-8")
    except OSError as error:
        raise ValueError(f"could not read scorer output {path}: {error}") from error

    clean: dict[str, int] = {}
    dirty: dict[str, int] = {}
    with handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames != ["vector", "bytes", "frame", "status", "gas"]:
            raise ValueError(f"unexpected scorer CSV header: {reader.fieldnames}")
        for row in reader:
            label = row["vector"]
            frame = row["frame"]
            status = row["status"]
            if not status.startswith("ok"):
                raise ValueError(f"scorer rejected {label}/{frame}: {status}")
            try:
                gas = int(row["gas"])
            except (TypeError, ValueError) as error:
                raise ValueError(f"invalid gas for {label}/{frame}: {row['gas']}") from error
            if gas < 0:
                raise ValueError(f"negative gas for {label}/{frame}")
            target = clean if frame == "clean" else dirty if frame == "dirty" else None
            if target is None:
                raise ValueError(f"unexpected scorer frame: {frame}")
            if label in target:
                raise ValueError(f"duplicate scorer row: {label}/{frame}")
            target[label] = gas

    if len(clean) != EXPECTED_VECTOR_COUNT or clean.keys() != dirty.keys():
        raise ValueError(
            f"expected {EXPECTED_VECTOR_COUNT} paired vectors, got "
            f"{len(clean)} clean and {len(dirty)} dirty"
        )
    return sum(clean.values()), sum(dirty.values()), len(clean)


def write_score(artifact_path: Path, csv_path: Path) -> None:
    _, artifact = read_artifact(artifact_path)
    clean_total, dirty_total, vector_count = parse_score_csv(csv_path)
    result = {
        "score": clean_total,
        "metrics": {
            "verified": True,
            "vectors": vector_count,
            "bytecodeBytes": len(artifact) // 2,
            "cleanTotalGas": clean_total,
            "dirtyTotalGas": dirty_total,
            "stateIndependentGas": clean_total == dirty_total,
        },
    }
    _atomic_write(Path("score.json"), json.dumps(result, indent=2) + "\n")

    summary = (
        "## EIP-8200 SHA-256 benchmark\n\n"
        f"- Verified clean-state gas: **{clean_total:,}**\n"
        f"- Dirty-state gas: **{dirty_total:,}**\n"
        f"- Bytecode size: **{len(artifact) // 2:,} bytes**\n"
        f"- Correctness vectors: **{vector_count}/{EXPECTED_VECTOR_COUNT} paired clean/dirty**\n"
        "- Lean Comparator: **accepted**\n"
    )
    _atomic_write(Path("benchmark-results/summary.md"), summary)


def usage() -> str:
    return (
        "usage:\n"
        "  yukon_benchmark.py prepare SUBMITTED_HEX TRUSTED_HEX ARTIFACT_MODULE CHALLENGE\n"
        "  yukon_benchmark.py score TRUSTED_HEX SCORER_CSV"
    )


def main() -> None:
    try:
        command = sys.argv[1]
        arguments = sys.argv[2:]
    except IndexError:
        raise SystemExit(usage()) from None

    try:
        if command == "prepare" and len(arguments) == 4:
            prepare(*(Path(argument) for argument in arguments))
        elif command == "score" and len(arguments) == 2:
            write_score(*(Path(argument) for argument in arguments))
        else:
            raise SystemExit(usage())
    except ValueError as error:
        raise SystemExit(str(error)) from error


if __name__ == "__main__":
    main()
